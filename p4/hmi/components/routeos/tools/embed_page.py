"""Turn the setup page's files into a C++ header the firmware serves from flash.

Run it after editing anything in web/:

    python tools/embed_page.py

The generated header is committed, because the firmware build (CMake + ESP-IDF) should not need Python on every
machine that compiles it.
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
WEB = HERE / "web"
OUT = HERE / "ros_page_assets.h"

FILES = [
    ("PAGE_HTML", "setup.html", "ROS_HTML"),
    ("PAGE_CSS", "paper.css", "ROS_CSS"),
    ("PAGE_TOOL_CSS", "tool.css", "ROS_TOOL"),
    ("PAGE_JS", "paper.js", "ROS_PAPERJS"),
    ("PAGE_SETUP_JS", "setup.js", "ROS_SETUPJS"),
]


def main():
    parts = [
        "// Generated by tools/embed_page.py - edit the files in web/ instead.",
        "#pragma once",
        "",
    ]
    for name, filename, delimiter in FILES:
        text = (WEB / filename).read_text(encoding="utf-8")
        if f"){delimiter}\"" in text:
            raise SystemExit(f"{filename} contains the raw-string delimiter, pick another one")
        parts.append(f"static const char {name}[] = R\"{delimiter}({text}){delimiter}\";")
        parts.append(f"static const unsigned {name}_LEN = {len(text.encode('utf-8'))};")
        parts.append("")
    OUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
